//! Import's settings (decision 85; `docs/library.md`, Import in folder mode): those the
//! settings schema gives `owner = "import"`, generated by `build.rs` as typed statics in
//! [`registry`], each darktable's conf key under its default, and [`ImportSettings`], what
//! the preview and the copy are given.
//!
//! This crate opens no folder or file of settings, as the engine opens none (decision 43):
//! a client opens a store on [`registry::ALL`] and fills an [`ImportSettings`] from it,
//! [`ImportSettings::read`]; the app keeps them as darktable keeps its conf, the CLI reads
//! them, `--conf` and its flags over them. Each key comes with the slice that first uses it:
//! 20a1's are the folder, the default folder, the subfolder and the import name.

use apertrust_base::settings::Store;
use serde::{Deserialize, Serialize};

pub use apertrust_base::variables::Places;

/// Import's settings as the settings schema declares them, generated from it by `build.rs`
/// as typed statics, each named after its id, and `ALL`, every one of them, for the store a
/// client opens (decisions 43 and 85).
pub mod registry {
    include!(concat!(env!("OUT_DIR"), "/settings.rs"));
}

use registry::{IMPORT_BASE_FOLDER, IMPORT_DEFAULT_FOLDER, IMPORT_JOB_CODE, IMPORT_SUBFOLDER};

/// An import's settings as plain data, what a client sends with `PreviewImport` and
/// `Import`, as an export's are `ExportSettings`: the patterns of darktable's variables as
/// the settings hold them, the import name, and the client's [`Places`], which the patterns
/// expand from, since the engine reads no platform folder (decision 43). In 20a1 every
/// photo keeps its camera name and no date overrides today's; File name, Keep original file
/// name and the override come with 20a2.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ImportSettings {
    /// Folder, `import.base_folder`.
    pub base_folder: String,
    /// The person's usual base folder, `import.default_folder`, whose tree the check for
    /// photos imported before walks too.
    pub default_folder: String,
    /// Subfolder, `import.subfolder`, worked out for each photo; empty puts them straight
    /// into the folder.
    pub subfolder: String,
    /// Import name, `import.job_code`, which `$(IMPORT_NAME)` and `$(JOBCODE)` expand to.
    pub job_code: String,
    pub places: Places,
}

impl ImportSettings {
    /// The settings `store` holds, with the client's `places`.
    pub fn read(store: &Store, places: Places) -> Self {
        ImportSettings {
            base_folder: store.get(&IMPORT_BASE_FOLDER),
            default_folder: store.get(&IMPORT_DEFAULT_FOLDER),
            subfolder: store.get(&IMPORT_SUBFOLDER),
            job_code: store.get(&IMPORT_JOB_CODE),
            places,
        }
    }
}

#[cfg(test)]
mod tests {
    use apertrust_base::settings::{Applies, Owner};

    use super::*;

    /// darktable's conf keys for 20a1's four, with their defaults
    /// (`data/darktableconfig.xml.in` at the reference release): Folder's folder
    /// `Apertrust` where darktable's says `Darktable`, and darktable's `$(JOBCODE)` under
    /// Apertrust's name for it (decision 85).
    #[test]
    fn the_import_settings_are_generated_from_the_schema_with_darktable_s_defaults() {
        let ids: Vec<&str> = registry::ALL.iter().map(|setting| setting.id()).collect();
        assert_eq!(
            ids,
            [
                "import.base_folder",
                "import.default_folder",
                "import.subfolder",
                "import.job_code"
            ]
        );
        assert_eq!(IMPORT_BASE_FOLDER.default(), "$(PICTURES_FOLDER)/Apertrust");
        assert_eq!(
            IMPORT_DEFAULT_FOLDER.default(),
            "$(PICTURES_FOLDER)/Apertrust"
        );
        assert_eq!(
            IMPORT_SUBFOLDER.default(),
            "$(YEAR)$(MONTH)$(DAY)_$(IMPORT_NAME)"
        );
        assert_eq!(IMPORT_JOB_CODE.default(), "no_name");
        for setting in [&IMPORT_BASE_FOLDER, &IMPORT_SUBFOLDER, &IMPORT_JOB_CODE] {
            assert_eq!(setting.owner, Owner::Import, "{}", setting.id);
        }
        assert_eq!(IMPORT_DEFAULT_FOLDER.owner, Owner::Import);
        for setting in registry::ALL {
            assert_eq!(setting.applies(), Applies::AtOnce, "{}", setting.id());
            assert_eq!(setting.page(), None, "{}: no row before 20a2", setting.id());
        }
    }

    #[test]
    fn the_settings_are_read_from_the_store_with_the_client_s_places() {
        let places = Places {
            home: Some("/home/ana".into()),
            ..Places::default()
        };
        let store = Store::nowhere(registry::ALL);
        let settings = ImportSettings::read(&store, places.clone());
        assert_eq!(settings.base_folder, "$(PICTURES_FOLDER)/Apertrust");
        assert_eq!(settings.subfolder, "$(YEAR)$(MONTH)$(DAY)_$(IMPORT_NAME)");
        assert_eq!(settings.job_code, "no_name");
        assert_eq!(settings.places, places);
    }
}

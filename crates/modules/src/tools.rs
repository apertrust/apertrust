//! The modules' tool settings (decisions 29 and 43; `docs/settings.md`, Tool settings):
//! darktable's own settings for a module's tool, which it keeps in its darktablerc and
//! never in an edit, as the settings schema declares them under `[tools.<module>]` with
//! `owner = "module:<module>"`, generated by `build.rs` as typed statics in [`registry`].
//!
//! A module's [`Row::ToolSetting`](crate::Row::ToolSetting) gives its kind, range,
//! options and default as darktable has them, and its setting here is found by its id,
//! `tools.<module>.<setting>` ([`setting`]); a test holds the two to agree. A row with no
//! setting here belongs to a tool still to come, drawn disabled at its default.
//!
//! This crate opens no folder or file of settings, as the engine opens none (decision 43):
//! the app opens a store on [`registry::ALL`] with its own settings, and sends the values
//! with the commands that run the tool (`PickerCommand::On` and `Tools`).

use apertrust_base::settings::Declared;

/// The tool settings as the settings schema declares them, generated from it by `build.rs`
/// as typed statics, each named after its id, and `ALL`, every one of them, for the store
/// a client opens.
pub mod registry {
    include!(concat!(env!("OUT_DIR"), "/settings.rs"));
}

/// The id a module's tool setting has in the settings: `tools.<module>.<setting>`.
pub fn id(module: &str, setting: &str) -> String {
    format!("tools.{module}.{setting}")
}

/// `module`'s tool setting `setting` as the settings declare it, if its tool keeps it.
pub fn setting(module: &str, setting: &str) -> Option<&'static dyn Declared> {
    let id = id(module, setting);
    registry::ALL.iter().copied().find(|s| s.id() == id)
}

#[cfg(test)]
mod tests {
    use apertrust_base::settings::{Kind, Owner};

    use super::*;
    use crate::{ControlKind, MODULES, Row};

    /// Every tool setting the schema declares is a row of its module's page, with the
    /// row's kind, range, decimals, options and default, darktable's.
    #[test]
    fn each_declared_tool_setting_is_its_module_s_row() {
        for declared in registry::ALL {
            let mut parts = declared.id().split('.');
            let (Some("tools"), Some(module), Some(name), None) =
                (parts.next(), parts.next(), parts.next(), parts.next())
            else {
                panic!("{} is not tools.<module>.<setting>", declared.id());
            };
            let found = MODULES
                .iter()
                .find(|m| m.definition().id == module)
                .unwrap_or_else(|| panic!("no module {module}"));
            let row = found
                .definition()
                .rows()
                .find_map(|row| match row {
                    Row::ToolSetting(setting) if setting.id == name => Some(setting),
                    _ => None,
                })
                .unwrap_or_else(|| panic!("{module} has no tool setting {name}"));
            assert!(std::ptr::eq(setting(module, name).unwrap(), *declared));
            match (row.kind, declared.kind()) {
                (
                    ControlKind::Number {
                        min,
                        max,
                        step,
                        default,
                    },
                    Kind::Number(number),
                ) => {
                    assert_eq!(number.min, Some(min), "{name}");
                    assert_eq!(number.max, Some(max), "{name}");
                    assert_eq!(number.step, Some(step), "{name}");
                    assert_eq!(number.decimals, Some(u32::from(row.decimals)), "{name}");
                    assert_eq!(
                        declared.default_value().and_then(|v| v.as_float()),
                        Some(f64::from(default)),
                        "{name}"
                    );
                }
                (
                    ControlKind::Choice {
                        options, default, ..
                    },
                    Kind::Choice(_),
                ) => {
                    assert_eq!(declared.options(), options, "{name}");
                    assert_eq!(
                        declared
                            .default_value()
                            .and_then(|v| v.as_str().map(str::to_owned)),
                        Some(options[default as usize].to_owned()),
                        "{name}"
                    );
                }
                (ControlKind::Bool { default }, Kind::Boolean) => {
                    assert_eq!(
                        declared.default_value().and_then(|v| v.as_bool()),
                        Some(default),
                        "{name}"
                    );
                }
                (kind, declared) => panic!("{name}: {kind:?} is declared {declared:?}"),
            }
        }
        // Owned by their module, as the generator gives them.
        assert!(
            registry::ALL
                .iter()
                .all(|s| s.id().starts_with("tools.exposure."))
        );
        assert!(matches!(
            registry::TOOLS_EXPOSURE_LIGHTNESS.owner,
            Owner::Module("exposure")
        ));
    }

    /// Every tool setting a module's built pick reads is kept: Exposure's.
    #[test]
    fn exposure_s_tool_settings_are_kept() {
        let ids: Vec<&str> = registry::ALL.iter().map(|s| s.id()).collect();
        assert_eq!(
            ids,
            ["tools.exposure.area_mode", "tools.exposure.lightness"]
        );
        assert!(setting("exposure", "lightness").is_some());
        // Colour calibration's still drawn disabled, its tool to come.
        assert!(setting("channelmixerrgb", "area_mode").is_none());
    }
}

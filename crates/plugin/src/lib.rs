//! Apertrust's operation interface (architecture decisions 4 and 20). An operation is
//! one algorithm in the engine, usually a darktable port, in a crate of its own under
//! `crates/op/`. It implements [`Operation`]: a [`Manifest`] saying where it
//! runs, a [`Schema`] of its parameters, its [`Kernel`], and `prepare`, which turns
//! parameter values into the passes the engine dispatches (`docs/engine.md`). The
//! engine works through this trait alone and never depends on an operation crate.
//!
//! Every image kernel uses the same bindings:
//!
//! - `@group(0) @binding(0)`: input pixels, `array<vec4<f32>>` read-only, rows top to
//!   bottom
//! - `@group(0) @binding(1)`: output pixels, same layout, read-write
//! - `@group(0) @binding(2)`: the uniform block: a [`PassHeader`], then the operation's
//!   own parameter struct at offset [`PassHeader::SIZE`]
//! - `@group(0) @binding(3)` and up: the operation's read-only tables (e.g. a gamut LUT)
//! - entry point `main` with `@workgroup_size(16, 16)`, one invocation per pixel
//!
//! A pass whose image is larger than the GPU binds at once runs in row strips, if it
//! says how ([`Strips`]): the engine binds a window of each image buffer per strip, and
//! the kernel finds the strip's first row in the header's origin and the windows' starts
//! in its `input_base` and `output_base`, indexing the whole image less them (decision
//! 14). The raw stage's kernels before demosaic do, and the engine's `region` copy;
//! demosaic and the kernels after it run whole or in tiles of their own instead.
//!
//! An operation that moves pixels returns a [`Geometry`], its region and point maps
//! (decision 16). Each image after the raw stage is a region of its stage's image
//! ([`ImageDesc`]'s `extent` and `origin`), and the header's origin and full size are
//! its operation's: its output region's corner and its stage's extent. A geometry's
//! kernel takes no row strips; it reads its input region and writes its output region.
//!
//! Each kernel keeps its parts apart so per-pixel operations can later be fused into one
//! kernel (decision 8): a parameter struct, any once-per-image setup, and a pure
//! per-pixel function of the pixel and those parameters.
//!
//! A darktable port also exports two derivative entry points, generated by Slang's
//! automatic differentiation. Both read input pixels (binding 0), parameters and tables
//! as `main` does, plus one `array<vec4<f32>>` per pixel at binding 8, and write one at
//! binding 9. Parameters come in up to four, in an order each operation documents.
//!
//! - `<operation>_backward`, reverse mode: reads dLoss/dOutput (RGB) and writes the
//!   gradient of the loss with respect to the parameters.
//! - `<operation>_forward_diff`, forward mode: reads a direction in parameter space and
//!   writes the output's directional derivative (RGB). It checks the reverse mode.


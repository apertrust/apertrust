//! The engine's settings (decision 43; `docs/settings.md`, The settings schema):
//! those the settings schema gives `owner = "engine"`, generated by `build.rs` as typed
//! statics in [`registry`], and [`Options`], which turns a store's values into the plain
//! options the engine takes, as [`cache_limit`] turns the cache's size settings into its
//! [`Limit`].
//!
//! The engine never opens a folder or a file of settings. A binary finds its user data
//! folder, opens a store on its `settings.toml` (the app's, which writes, on the app's
//! registry and this one; the CLI's, which never writes, on this one), holding its
//! `--conf` values over the file, and hands it here with its own flags. The golden
//! harness opens none, so no result of its depends on a person's folder: it takes
//! [`GpuOptions::default`] and [`pipeline::BUDGET`](crate::pipeline::BUDGET), these
//! settings' defaults.

use std::fmt;

use apertrust_base::cache::Limit;
use apertrust_base::settings::{CONF_FLAG, Declared, Store};

use crate::gpu::{AdapterChoice, GpuOptions};

/// The engine's settings as the settings schema declares them, generated from it by
/// `build.rs` as typed statics, each named after its id, and `ALL`, every one of them, for
/// the store a binary opens (decision 43).
pub mod registry {
    include!(concat!(env!("OUT_DIR"), "/settings.rs"));
}

use registry::{CACHE_LIMIT, CACHE_LIMITED, ENGINE_ADAPTER, ENGINE_MEMORY_BUDGET};

/// A gigabyte of `cache.limit`, as disks count it.
const GB: f64 = 1e9;

/// The cache's limit in `store` (decision 76): [`Limit::Unlimited`] while `cache.limited`
/// is off, else `cache.limit`'s gigabytes in bytes.
pub fn cache_limit(store: &Store) -> Limit {
    if !store.get(&CACHE_LIMITED) {
        return Limit::Unlimited;
    }
    let gigabytes = f64::from(store.get(&CACHE_LIMIT));
    Limit::Bytes((gigabytes * GB).round() as u64)
}

/// The flag a binary takes for `engine.adapter`.
pub const ADAPTER_FLAG: &str = "--adapter";

/// A binary's own flags over the engine's settings, for one run, each before `--conf` and
/// the settings file (decision 43).
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Flags {
    /// `--adapter NAME`: the first adapter whose name contains it, an error where none
    /// does; empty, wgpu's choice, whatever the file says.
    pub adapter: Option<String>,
}

/// Where a setting's value came from, as `-d settings` names it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Source {
    /// A binary's own flag, by its name.
    Flag(&'static str),
    /// `--conf KEY=VALUE`, which the store holds over the file for this run.
    Conf,
    /// The settings file, which the store read.
    File,
    /// The schema's default.
    Default,
}

impl Source {
    /// Where `store`'s value of `setting` came from, given it keeps one: `--conf` or the
    /// file.
    fn kept(store: &Store, setting: &dyn Declared) -> Source {
        if store.overridden(setting) {
            Source::Conf
        } else {
            Source::File
        }
    }
}

impl fmt::Display for Source {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Source::Flag(flag) => flag,
            Source::Conf => CONF_FLAG,
            Source::File => "file",
            Source::Default => "default",
        })
    }
}

/// The engine's settings as the plain options it takes.
#[derive(Clone, Debug)]
pub struct Options {
    /// The device to open: `engine.adapter`'s adapter, the rest as
    /// [`GpuOptions::default`], for a binary's developer switches to lower
    /// (`--max-binding`).
    pub gpu: GpuOptions,
    /// `engine.memory_budget` in bytes: the GPU memory a render may take before it tiles
    /// (decision 12), for an export's `Tiling::Auto` and a plan's `Limits`.
    pub budget: u64,
    /// Where each came from: the adapter's, then the budget's.
    pub sources: [Source; 2],
}

impl Options {
    /// The engine's settings in `store`, which a binary opened on a registry holding
    /// [`registry::ALL`] with its `--conf` values, under its own `flags`: a flag of its own
    /// first, then `--conf`, then the file, then the default. Logs each value and where it
    /// came from, under `-d settings`.
    ///
    /// An adapter named for this run, by `--adapter` or `--conf`, must be there, since what
    /// was typed for the run is never ignored; one the file names falls back to wgpu's
    /// choice.
    pub fn read(store: &Store, flags: &Flags) -> Options {
        let (name, adapter_from) = match (&flags.adapter, store.kept(&ENGINE_ADAPTER)) {
            (Some(name), _) => (name.clone(), Source::Flag(ADAPTER_FLAG)),
            (None, Some(name)) => (name, Source::kept(store, &ENGINE_ADAPTER)),
            (None, None) => (ENGINE_ADAPTER.default().to_owned(), Source::Default),
        };
        let (adapter, shown) = match adapter_from {
            _ if name.is_empty() => (AdapterChoice::Any, "wgpu's choice".to_owned()),
            Source::Flag(_) | Source::Conf => {
                (AdapterChoice::Named(name.clone()), format!("{name:?}"))
            }
            Source::File | Source::Default => {
                (AdapterChoice::Preferred(name.clone()), format!("{name:?}"))
            }
        };
        let (mib, budget_from) = match store.kept(&ENGINE_MEMORY_BUDGET) {
            Some(mib) => (mib, Source::kept(store, &ENGINE_MEMORY_BUDGET)),
            None => (ENGINE_MEMORY_BUDGET.default(), Source::Default),
        };
        // Kept whole: a value read with decimals is rounded.
        let mib = mib.round() as u64;
        let (adapter_id, budget_id) = (ENGINE_ADAPTER.id, ENGINE_MEMORY_BUDGET.id);
        tracing::debug!(target: "settings", "{adapter_id}: {shown}, from: {adapter_from}");
        tracing::debug!(target: "settings", "{budget_id}: {mib} MiB, from: {budget_from}");
        Options {
            gpu: GpuOptions {
                adapter,
                ..GpuOptions::default()
            },
            budget: mib << 20,
            sources: [adapter_from, budget_from],
        }
    }
}

#[cfg(test)]
mod tests {
    use std::io;
    use std::path::Path;

    use apertrust_base::cache::UnusedAfter;
    use apertrust_base::settings::{Applies, Overrides, Owner, Storage};

    use super::*;

    /// Settings held in a text, read and never written.
    struct Text(&'static str);

    impl Storage for Text {
        fn location(&self) -> String {
            "settings.toml".to_owned()
        }

        fn read(&self) -> io::Result<Option<String>> {
            Ok((!self.0.is_empty()).then(|| self.0.to_owned()))
        }

        fn write(&mut self, _: &str) -> io::Result<()> {
            unreachable!("a store that never writes")
        }

        fn set_aside(&mut self) -> io::Result<String> {
            unreachable!("a store that never writes")
        }
    }

    /// The options `file` and `flags` give.
    fn read(file: &'static str, flags: Flags) -> Options {
        read_with(file, &[], flags)
    }

    /// The options `file`, `--conf`'s `conf` and `flags` give.
    fn read_with(file: &'static str, conf: &[&str], flags: Flags) -> Options {
        let overrides = Overrides::read(conf, registry::ALL).expect("read");
        let store = Store::read_only(&Text(file), registry::ALL).with_overrides(&overrides);
        Options::read(&store, &flags)
    }

    fn flag(adapter: &str) -> Flags {
        Flags {
            adapter: Some(adapter.to_owned()),
        }
    }

    #[test]
    fn the_engine_s_settings_are_generated_from_the_schema() {
        let ids: Vec<&str> = registry::ALL.iter().map(|setting| setting.id()).collect();
        assert_eq!(
            ids,
            [
                "library.raw_thumbnails_from",
                "engine.adapter",
                "engine.memory_budget",
                "cache.limited",
                "cache.limit",
                "cache.unused_after"
            ]
        );
        assert_eq!(registry::CACHE_LIMIT.requires, Some(CACHE_LIMITED.id));
        assert_eq!(registry::CACHE_UNUSED_AFTER.default(), UnusedAfter::Days90);
        assert_eq!(ENGINE_ADAPTER.owner, Owner::Engine);
        assert_eq!(ENGINE_ADAPTER.default(), "");
        assert_eq!(ENGINE_ADAPTER.applies, Applies::AfterRestart);
        assert_eq!(ENGINE_MEMORY_BUDGET.owner, Owner::Engine);
        assert_eq!(ENGINE_MEMORY_BUDGET.default(), 2048.0);
        assert_eq!(ENGINE_MEMORY_BUDGET.applies, Applies::AfterRestart);
        assert_eq!(ENGINE_MEMORY_BUDGET.range(), 256.0..=65536.0);
    }

    /// The golden harness reads no settings: it takes the engine's own defaults, which are
    /// what a person without a settings file gets, so its results depend on no folder.
    #[test]
    fn the_defaults_are_those_the_golden_harness_takes() {
        let options = Options::read(&Store::nowhere(registry::ALL), &Flags::default());
        assert_eq!(options.gpu.adapter, GpuOptions::default().adapter);
        assert_eq!(options.gpu.adapter, AdapterChoice::Any);
        assert_eq!(options.budget, crate::pipeline::BUDGET);
        assert_eq!(options.sources, [Source::Default, Source::Default]);
    }

    #[test]
    fn a_flag_comes_before_the_file_and_the_file_before_the_default() {
        let file = "version = 1\n[engine]\nadapter = \"Radeon\"\nmemory_budget = 4096\n";
        let from_file = read(file, Flags::default());
        assert_eq!(
            from_file.gpu.adapter,
            AdapterChoice::Preferred("Radeon".to_owned())
        );
        assert_eq!(from_file.budget, 4096 << 20);
        assert_eq!(from_file.sources, [Source::File, Source::File]);

        let from_flag = read(file, flag("M4"));
        assert_eq!(from_flag.gpu.adapter, AdapterChoice::Named("M4".to_owned()));
        assert_eq!(from_flag.budget, 4096 << 20);
        assert_eq!(from_flag.sources, [Source::Flag("--adapter"), Source::File]);

        // An empty flag takes wgpu's choice over the file's adapter.
        let emptied = read(file, flag(""));
        assert_eq!(emptied.gpu.adapter, AdapterChoice::Any);
        assert_eq!(emptied.sources[0], Source::Flag("--adapter"));

        let none = read("", Flags::default());
        assert_eq!(
            (none.gpu.adapter, none.budget, none.sources),
            (AdapterChoice::Any, 2048 << 20, [Source::Default; 2])
        );
        // An empty one in the file, and a budget out of range read as the nearer end, or
        // with decimals, rounded.
        let file = "version = 1\n[engine]\nadapter = \"\"\nmemory_budget = 100\n";
        let clamped = read(file, Flags::default());
        assert_eq!(
            (clamped.gpu.adapter, clamped.budget),
            (AdapterChoice::Any, 256 << 20)
        );
        let rounded = read(
            "version = 1\nengine.memory_budget = 3000.6\n",
            Flags::default(),
        );
        assert_eq!(rounded.budget, 3001 << 20);
    }

    /// A flag of its own, then `--conf`, then the file, then the default (decision 43).
    #[test]
    fn a_conf_comes_after_a_flag_and_before_the_file() {
        let file = "version = 1\n[engine]\nadapter = \"Radeon\"\nmemory_budget = 4096\n";
        let conf = ["engine.adapter=RTX", "engine.memory_budget=1024"];
        let from_conf = read_with(file, &conf, Flags::default());
        // Named for this run, so one that names no adapter is an error, as `--adapter`'s.
        assert_eq!(
            from_conf.gpu.adapter,
            AdapterChoice::Named("RTX".to_owned())
        );
        assert_eq!(from_conf.budget, 1024 << 20);
        assert_eq!(from_conf.sources, [Source::Conf, Source::Conf]);
        assert_eq!(Source::Conf.to_string(), "--conf");

        let from_flag = read_with(file, &conf, flag("M4"));
        assert_eq!(from_flag.gpu.adapter, AdapterChoice::Named("M4".to_owned()));
        assert_eq!(from_flag.sources, [Source::Flag("--adapter"), Source::Conf]);

        // Over the default too; an empty one takes wgpu's choice.
        let over_default = read_with("", &["engine.adapter="], Flags::default());
        assert_eq!(over_default.gpu.adapter, AdapterChoice::Any);
        assert_eq!(over_default.sources, [Source::Conf, Source::Default]);
        // Out of range, the nearer end, as the file's.
        let clamped = read_with(file, &["engine.memory_budget=100"], Flags::default());
        assert_eq!(clamped.budget, 256 << 20);
        assert_eq!(clamped.sources, [Source::File, Source::Conf]);
    }

    /// Unlimited while `cache.limited` is off, whatever `cache.limit` says; else the limit
    /// in bytes, by the file's rules and `--conf`'s alike.
    #[test]
    fn the_cache_s_settings_give_its_limit() {
        let limit = |file, conf: &[&str]| {
            let overrides = Overrides::read(conf, registry::ALL).expect("read");
            let store = Store::read_only(&Text(file), registry::ALL).with_overrides(&overrides);
            cache_limit(&store)
        };
        assert_eq!(limit("", &[]), Limit::Bytes(4_000_000_000));
        let file = "version = 1\n[cache]\nlimit = 12.5\n";
        assert_eq!(limit(file, &[]), Limit::Bytes(12_500_000_000));
        let off = "version = 1\n[cache]\nlimited = false\nlimit = 12.5\n";
        assert_eq!(limit(off, &[]), Limit::Unlimited);
        assert_eq!(
            limit(off, &["cache.limited=true"]),
            Limit::Bytes(12_500_000_000)
        );
        assert_eq!(limit(file, &["cache.limited=false"]), Limit::Unlimited);
        // Out of range, the nearer end: half a gigabyte, a thousand.
        assert_eq!(limit(file, &["cache.limit=0.1"]), Limit::Bytes(500_000_000));
        let most = "version = 1\ncache.limit = 5000\n";
        assert_eq!(limit(most, &[]), Limit::Bytes(1_000_000_000_000));
    }

    /// The engine opens no folder or file of settings (decision 43): its manifest takes
    /// base's settings part, its jobs (decision 57) and its cache (decision 76), never its
    /// folders, and no code of
    /// its opens a store or names the file; only the binaries do.
    #[test]
    fn the_engine_reads_no_settings_file_itself() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        let manifest = std::fs::read_to_string(root.join("Cargo.toml")).expect("the manifest");
        let base: Vec<&str> = manifest
            .lines()
            .filter(|line| line.starts_with("apertrust-base"))
            .collect();
        assert_eq!(
            base,
            [
                "apertrust-base = { workspace = true, features = [\"jobs\", \"cache\"] }",
                "apertrust-base = { workspace = true, features = [\"codegen\"] }",
            ]
        );
        // Nor do base's defaults turn its folders on.
        let base = std::fs::read_to_string(root.join("../base/Cargo.toml")).expect("base's");
        let features = base
            .split("\n[features]\n")
            .nth(1)
            .expect("base's features");
        let features = features.split("\n[").next().unwrap_or_default();
        let mut keys = features.lines().filter_map(|line| line.split('=').next());
        assert!(
            !keys.any(|key| key.trim() == "default"),
            "apertrust-base has default features: {features}"
        );
        let mut folders = vec![root.join("src")];
        while let Some(folder) = folders.pop() {
            for entry in std::fs::read_dir(&folder).expect("the sources") {
                let path = entry.expect("an entry").path();
                if path.is_dir() {
                    folders.push(path);
                    continue;
                }
                let text = std::fs::read_to_string(&path).expect("a source");
                // Its code, not its comments or its tests.
                let code = text.split("\n#[cfg(test)]\nmod tests").next();
                let code = code.unwrap_or_default().lines();
                let code = code.filter(|l| !l.trim_start().starts_with("//"));
                let opening = [
                    "FileStorage",
                    "Store::open",
                    "Store::read_only",
                    "apertrust_base::folders",
                    "Folders::",
                ];
                for line in code {
                    for opens in opening {
                        assert!(!line.contains(opens), "{}: {line}", path.display());
                    }
                }
            }
        }
    }
}

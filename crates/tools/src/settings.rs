//! The tools' settings (decisions 29 and 43; `docs/pickers.md`, A tool's settings):
//! darktable's own settings for a module, which it keeps in its darktablerc and never in
//! an edit, as the settings schema declares them under `[tools.<tool>]` with
//! `owner = "tool:<tool>"`, generated by `build.rs` as typed statics in [`registry`].
//!
//! A tool's [`Row::Setting`](crate::Row::Setting) gives its kind, range, options and
//! default as darktable has them, and its setting here is found by its id,
//! `tools.<tool>.<setting>` ([`setting`]); a test holds the two to agree. A row with no
//! setting here belongs to a feature still to be built, drawn disabled at its default.
//!
//! This crate opens no folder or file of settings, as the engine opens none (decision 43):
//! the app opens a store on [`registry::ALL`] with its own settings, and sends the values
//! with the commands that use them (`PickerCommand::On` and `Settings`).

use apertrust_base::settings::Declared;

/// The tools' settings as the settings schema declares them, generated from it by `build.rs`
/// as typed statics, each named after its id, and `ALL`, every one of them, for the store
/// a client opens.
pub mod registry {
    include!(concat!(env!("OUT_DIR"), "/settings.rs"));
}

/// The id a tool's setting has in the settings: `tools.<tool>.<setting>`.
pub fn id(tool: &str, setting: &str) -> String {
    format!("tools.{tool}.{setting}")
}

/// `tool`'s setting `setting` as the settings declare it, if it is kept.
pub fn setting(tool: &str, setting: &str) -> Option<&'static dyn Declared> {
    let id = id(tool, setting);
    registry::ALL.iter().copied().find(|s| s.id() == id)
}

#[cfg(test)]
mod tests {
    use apertrust_base::settings::{Kind, Owner};

    use super::*;
    use crate::{ControlKind, Row, TOOLS};

    /// Every tool setting the schema declares is a row of its tool's page, with the
    /// row's kind, range, decimals, options and default, darktable's.
    #[test]
    fn each_declared_setting_is_its_tool_s_row() {
        for declared in registry::ALL {
            let mut parts = declared.id().split('.');
            let (Some("tools"), Some(tool), Some(name), None) =
                (parts.next(), parts.next(), parts.next(), parts.next())
            else {
                panic!("{} is not tools.<tool>.<setting>", declared.id());
            };
            let found = TOOLS
                .iter()
                .find(|m| m.definition().id == tool)
                .unwrap_or_else(|| panic!("no tool {tool}"));
            // A reference row's two (decision 88): its L, an optional percentage, and its
            // photo's path, an optional text.
            let reference = found.definition().rows().find_map(|row| match row {
                Row::Reference {
                    lightness, photo, ..
                } if *lightness == name || *photo == name => Some(*lightness == name),
                _ => None,
            });
            if let Some(is_lightness) = reference {
                assert_eq!(declared.default_value(), None, "{name}");
                match declared.kind() {
                    Kind::Number(number) if is_lightness => {
                        assert_eq!((number.min, number.max), (Some(0.0), Some(100.0)));
                        assert_eq!(number.decimals, Some(1), "{name}");
                    }
                    Kind::Text if !is_lightness => {}
                    kind => panic!("{name} is declared {kind:?}"),
                }
                continue;
            }
            let row = found
                .definition()
                .rows()
                .find_map(|row| match row {
                    Row::Setting(setting) if setting.id == name => Some(setting),
                    _ => None,
                })
                .unwrap_or_else(|| panic!("{tool} has no setting {name}"));
            assert!(std::ptr::eq(setting(tool, name).unwrap(), *declared));
            match (row.kind, declared.kind()) {
                (
                    ControlKind::Number {
                        min,
                        max,
                        step,
                        default,
                    },
                    Kind::Number(number),
                ) => {
                    assert_eq!(number.min, Some(min), "{name}");
                    assert_eq!(number.max, Some(max), "{name}");
                    assert_eq!(number.step, Some(step), "{name}");
                    assert_eq!(number.decimals, Some(u32::from(row.decimals)), "{name}");
                    assert_eq!(
                        declared.default_value().and_then(|v| v.as_float()),
                        Some(f64::from(default)),
                        "{name}"
                    );
                }
                (
                    ControlKind::Choice {
                        options, default, ..
                    },
                    Kind::Choice(_),
                ) => {
                    assert_eq!(declared.options(), options, "{name}");
                    assert_eq!(
                        declared
                            .default_value()
                            .and_then(|v| v.as_str().map(str::to_owned)),
                        Some(options[default as usize].to_owned()),
                        "{name}"
                    );
                }
                (ControlKind::Bool { default }, Kind::Boolean) => {
                    assert_eq!(
                        declared.default_value().and_then(|v| v.as_bool()),
                        Some(default),
                        "{name}"
                    );
                }
                (kind, declared) => panic!("{name}: {kind:?} is declared {declared:?}"),
            }
        }
        // Owned by their tool, as the generator gives them.
        assert!(
            registry::ALL
                .iter()
                .all(|s| s.id().starts_with("tools.exposure."))
        );
        assert!(matches!(
            registry::TOOLS_EXPOSURE_LIGHTNESS.owner,
            Owner::Tool("exposure")
        ));
    }

    /// Every setting a tool's built pick reads is kept: Exposure's, Picker target,
    /// Lightness and the reference.
    #[test]
    fn exposure_s_settings_are_kept() {
        let ids: Vec<&str> = registry::ALL.iter().map(|s| s.id()).collect();
        assert_eq!(
            ids,
            [
                "tools.exposure.target",
                "tools.exposure.lightness",
                "tools.exposure.reference_lightness",
                "tools.exposure.reference_photo",
            ]
        );
        assert!(setting("exposure", "lightness").is_some());
        // Colour calibration's still drawn disabled, its picker to come.
        assert!(setting("channelmixerrgb", "area_mode").is_none());
    }
}

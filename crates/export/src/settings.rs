    /// What darktable's conf reads for `id`'s key with nothing in darktablerc.
    fn darktable(id: &str) -> &'static str {
        let found = DARKTABLE.iter().find(|(ours, ..)| *ours == id);
        found
            .unwrap_or_else(|| panic!("no darktable key for {id}"))
            .2
    }

    /// `id`'s as `dt_conf_get_int` reads it: none is 0.
    fn int(id: &str) -> i32 {
        let text = darktable(id);
        if text.is_empty() {
            0
        } else {
            text.parse().expect("a number")
        }
    }

    /// `id`'s as `dt_conf_get_bool` reads it: false where it starts with F, f or 0, or is
    /// empty.
    fn boolean(id: &str) -> bool {
        !matches!(
            darktable(id).bytes().next(),
            None | Some(b'F' | b'f' | b'0')
        )
    }

    /// The option of `T` darktable's number for it names: its place in darktable's order.
    fn nth<T: Choice>(n: i32) -> T {
        T::OPTIONS[usize::try_from(n).expect("a place")].0
    }

    fn id<T: Choice + PartialEq>(value: T) -> &'static str {
        let option = T::OPTIONS.iter().find(|(option, _)| *option == value);
        option.expect("an option").1
    }

    fn ids<T: Choice>() -> Vec<&'static str> {
        T::OPTIONS.iter().map(|(_, id)| *id).collect()
    }

    #[test]
    fn the_export_settings_are_generated_from_the_schema() {
        let ids: Vec<&str> = registry::ALL.iter().map(|setting| setting.id()).collect();
        assert_eq!(ids, DARKTABLE.map(|(id, ..)| id));
        assert_eq!(EXPORT_JPEG_QUALITY.owner, Owner::Export);
        assert_eq!(EXPORT_DISK_PATH.owner, Owner::Export);
        assert_eq!(EXPORT_PROFILE.applies, Applies::AtOnce);
    }

    /// Every default darktable's, its key's as darktable reads it with nothing in
    /// darktablerc, but File on disk's folder, `apertrust_exported` (D6), and Scale's: "1",
    /// which darktable's reset and its first export write, where its conf reads none,
    /// both 1.
    #[test]
    fn every_default_is_darktable_s() {
        let path = darktable("export.disk.path").replace("darktable_", "apertrust_");
        assert_eq!(EXPORT_DISK_PATH.default(), path);
        assert_eq!(
            EXPORT_DISK_ON_CONFLICT.default(),
            nth(int("export.disk.on_conflict"))
        );
        assert_eq!(id(EXPORT_FORMAT.default()), darktable("export.format"));
        assert_eq!(
            EXPORT_JPEG_QUALITY.default(),
            int("export.jpeg.quality") as f32
        );
        assert_eq!(
            EXPORT_JPEG_SUBSAMPLE.default(),
            nth(int("export.jpeg.subsample"))
        );
        assert_eq!(
            id(EXPORT_PNG_BIT_DEPTH.default()),
            darktable("export.png.bit_depth")
        );
        assert_eq!(
            EXPORT_PNG_COMPRESSION.default(),
            int("export.png.compression") as f32
        );
        assert_eq!(EXPORT_SIZE_MODE.default(), nth(int("export.size.mode")));
        assert_eq!(EXPORT_SIZE_WIDTH.default(), int("export.size.width") as f32);
        assert_eq!(
            EXPORT_SIZE_HEIGHT.default(),
            int("export.size.height") as f32
        );
        assert_eq!(EXPORT_SIZE_DPI.default(), int("export.size.dpi") as f32);
        let scale = EXPORT_SIZE_SCALE.default();
        assert_eq!(scale, "1");
        assert_eq!(
            size::scale_factor(scale),
            size::scale_factor(darktable("export.size.scale"))
        );
        assert_eq!(
            EXPORT_SIZE_UPSCALE.default(),
            boolean("export.size.upscale")
        );
        assert_eq!(
            EXPORT_SIZE_HIGH_QUALITY.default(),
            boolean("export.size.high_quality")
        );
        // -1 is image settings, `DT_COLORSPACE_NONE`; the others darktable keeps by their
        // type, not by their place.
        assert_eq!(int("export.profile"), -1);
        assert_eq!(EXPORT_PROFILE.default(), Profile::ImageSettings);
        assert!(boolean("export.ask_before_overwrite"));
        assert_eq!(
            EXPORT_ASK_BEFORE_OVERWRITE.default(),
            boolean("export.ask_before_overwrite")
        );
        // And the writers' own defaults are these, as darktable-cli's would be.
        let store = Store::nowhere(registry::ALL);
        assert_eq!(
            format(&store, FileFormat::Jpeg),
            Format::Jpeg(jpeg::Options::default())
        );
        assert_eq!(
            format(&store, FileFormat::Png),
            Format::Png(png::Options::default())
        );
    }

    /// Each range darktable's (`darktableconfig.xml.in`'s `min` and `max`): JPEG's quality
    /// 5 to 100, PNG's compression 0 to 9, the dpi 72 to 9600, the sizes from 0 with no
    /// most; and each choice's options darktable's, in its order, so the number darktable
    /// keeps for one is its place, but the profile's, which darktable keeps by its type.
    #[test]
    fn each_range_and_each_choice_s_options_are_darktable_s() {
        assert_eq!(EXPORT_JPEG_QUALITY.range(), 5.0..=100.0);
        assert_eq!(EXPORT_PNG_COMPRESSION.range(), 0.0..=9.0);
        assert_eq!(EXPORT_SIZE_DPI.range(), 72.0..=9600.0);
        assert_eq!(EXPORT_SIZE_WIDTH.range(), 0.0..=f32::MAX);
        assert_eq!(EXPORT_SIZE_HEIGHT.range(), 0.0..=f32::MAX);
        // `dt_disk_onconflict_actions_t`, 0 to 3.
        assert_eq!(
            ids::<OnConflict>(),
            [
                "create_unique_filename",
                "overwrite",
                "overwrite_if_changed",
                "skip"
            ]
        );
        // `dt_imageio_jpeg_subsample_t`, 0 to 4.
        assert_eq!(
            ids::<jpeg::Subsample>(),
            ["auto", "444", "440", "422", "420"]
        );
        let options = jpeg::Subsample::OPTIONS.iter().map(|(option, _)| *option);
        assert!(options.eq(jpeg::Subsample::ALL));
        // `bpp`'s enum, as darktable declares it.
        assert_eq!(ids::<png::BitDepth>(), ["8", "16"]);
        // `dt_dimensions_type_t`, 0 to 3.
        assert_eq!(ids::<SizeMode>(), ["pixels", "cm", "inch", "scale"]);
        // darktable's names for the formats built.
        assert_eq!(ids::<FileFormat>(), ["jpeg", "png"]);
        // Image settings, which darktable keeps as -1, then its export profiles in `out_pos`
        // order, each kept as its `dt_colorspaces_color_profile_type_t`, sRGB's 1.
        assert_eq!(ids::<Profile>(), ["image_settings", "srgb"]);
    }

    /// A format's options are the file's, `--conf`'s over them for the run, as
    /// darktable-cli's are darktablerc's with darktable's `--conf` over them.
    #[test]
    fn a_format_s_options_are_the_file_s_and_conf_s_over_them() {
        let file = "version = 1\n[export]\nformat = \"png\"\n\
                    [export.jpeg]\nquality = 80\nsubsample = \"420\"\n\
                    [export.png]\nbit_depth = \"16\"\ncompression = 9\n";
        let from_file = read(file, &[]);
        assert_eq!(
            format(&from_file, FileFormat::Jpeg),
            Format::Jpeg(jpeg::Options {
                quality: 80,
                subsample: jpeg::Subsample::S420,
                dpi: 300,
            })
        );
        assert_eq!(
            format(&from_file, FileFormat::Png),
            Format::Png(png::Options {
                bit_depth: png::BitDepth::Sixteen,
                compression: 9,
            })
        );
        let conf = [
            "export.jpeg.quality=70",
            "export.png.bit_depth=8",
            "export.png.compression=0",
        ];
        let from_conf = read(file, &conf);
        assert_eq!(
            format(&from_conf, FileFormat::Jpeg),
            Format::Jpeg(jpeg::Options {
                quality: 70,
                subsample: jpeg::Subsample::S420,
                dpi: 300,
            })
        );
        // 0, zlib's none, a level all the same, where darktable takes 5 only for a key it
        // has never kept (`dt_conf_key_exists`).
        assert_eq!(
            format(&from_conf, FileFormat::Png),
            Format::Png(png::Options {
                bit_depth: png::BitDepth::Eight,
                compression: 0,
            })
        );
        // Out of range, the nearer end; with decimals, rounded; an option none of the
        // type's, the default, warned of.
        let file = "version = 1\n[export.jpeg]\nquality = 2\nsubsample = \"4:2:0\"\n\
                    [export.png]\ncompression = 6.6\n";
        let read = read(file, &[]);
        assert_eq!(
            format(&read, FileFormat::Jpeg),
            Format::Jpeg(jpeg::Options {
                quality: 5,
                ..jpeg::Options::default()
            })
        );
        assert_eq!(
            format(&read, FileFormat::Png),
            Format::Png(png::Options {
                compression: 7,
                ..png::Options::default()
            })
        );
        assert!(
            read.warnings()
                .iter()
                .any(|w| w.starts_with("export.jpeg.subsample")),
            "{:?}",
            read.warnings()
        );
    }

    /// A JPEG's density is the print dpi in the cm and inch modes, as darktable's export
    /// module sets `metadata/resolution` to it there and back to 300 in the others.
    #[test]
    fn a_jpeg_s_density_is_the_print_dpi_in_the_print_modes() {
        let dpi = |file: &str| match format(&read(file, &[]), FileFormat::Jpeg) {
            Format::Jpeg(options) => options.dpi,
            other => panic!("{other:?}"),
        };
        assert_eq!(
            dpi("version = 1\n[export.size]\nmode = \"cm\"\ndpi = 600\n"),
            600
        );
        assert_eq!(
            dpi("version = 1\n[export.size]\nmode = \"inch\"\ndpi = 72\n"),
            72
        );
        assert_eq!(dpi("version = 1\n[export.size]\nmode = \"inch\"\n"), 300);
        for mode in ["pixels", "scale"] {
            let file = format!("version = 1\n[export.size]\nmode = \"{mode}\"\ndpi = 600\n");
            assert_eq!(dpi(&file), 300, "{mode}");
        }
    }

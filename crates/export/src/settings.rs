//! The export settings (decision 56; `docs/engine.md`, Export jobs, Settings and
//! presets): the Export dialog's last settings, one per darktable conf key the
//! dialog holds, those the settings schema gives `owner = "export"`, generated by
//! `build.rs` as typed statics in [`registry`], with their choices' types, and
//! [`format()`], a format with the options a store holds.
//!
//! This crate opens no folder or file of settings, as the engine opens none (decision
//! 43): a client opens a store on [`registry::ALL`] and hands it here. The app is to keep
//! them as darktable keeps its conf, written as the dialog changes; the CLI reads them, as
//! darktable-cli reads darktablerc, and takes from them only what darktable-cli takes:
//! each format's options, through [`format()`], and, once File on disk comes, On
//! conflict, its own flags giving the rest.

use apertrust_base::settings::{Choice, Store};

use crate::{Format, jpeg, png};

/// The export settings as the settings schema declares them, generated from it by
/// `build.rs` as typed statics, each named after its id, and `ALL`, every one of them, for
/// the store a client opens (decisions 43 and 56).
pub mod registry {
    include!(concat!(env!("OUT_DIR"), "/settings.rs"));
}

use registry::{
    EXPORT_JPEG_QUALITY, EXPORT_JPEG_SUBSAMPLE, EXPORT_PNG_BIT_DEPTH, EXPORT_PNG_COMPRESSION,
    EXPORT_SIZE_DPI, EXPORT_SIZE_MODE,
};

/// File on disk's On conflict: darktable's four (`dt_disk_onconflict_actions_t`), in its
/// order, so the number darktable keeps for one is its place.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum OnConflict {
    /// `_01`, `_02` and on before the extension, the first that is free.
    #[default]
    CreateUniqueFilename,
    Overwrite,
    /// A file newer than the photo's edit is kept.
    OverwriteIfChanged,
    /// A file already there is kept.
    Skip,
}

impl Choice for OnConflict {
    const OPTIONS: &'static [(Self, &'static str)] = &[
        (Self::CreateUniqueFilename, "create_unique_filename"),
        (Self::Overwrite, "overwrite"),
        (Self::OverwriteIfChanged, "overwrite_if_changed"),
        (Self::Skip, "skip"),
    ];
}

/// The file format, by darktable's names for its formats (`format_name`), in darktable's
/// order. Its other formats come with their writers.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum FileFormat {
    #[default]
    Jpeg,
    Png,
}

impl Choice for FileFormat {
    const OPTIONS: &'static [(Self, &'static str)] = &[(Self::Jpeg, "jpeg"), (Self::Png, "png")];
}

/// Set size: darktable's four (`dt_dimensions_type_t`), in its order. In the print modes
/// the largest width and height are still kept in pixels, at the dpi, as darktable keeps
/// them ([`size::cm_to_pixels`](crate::size::cm_to_pixels)).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum SizeMode {
    #[default]
    Pixels,
    Cm,
    Inch,
    Scale,
}

impl Choice for SizeMode {
    const OPTIONS: &'static [(Self, &'static str)] = &[
        (Self::Pixels, "pixels"),
        (Self::Cm, "cm"),
        (Self::Inch, "inch"),
        (Self::Scale, "scale"),
    ];
}

/// The profile: the edit's own, or one of darktable's export profiles in its place for the
/// export alone (decision 26), by Output colour profile's ids for them. These two for now;
/// darktable's others come after decision 26's display conversion.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Profile {
    /// darktable's image settings (`icctype` -1): Output colour profile's Export profile,
    /// so the export matches the view.
    #[default]
    ImageSettings,
    /// sRGB (web-safe).
    Srgb,
}

impl Choice for Profile {
    const OPTIONS: &'static [(Self, &'static str)] = &[
        (Self::ImageSettings, "image_settings"),
        (Self::Srgb, "srgb"),
    ];
}

/// `format` with its options as `store` holds them, as darktable's format modules read
/// theirs from its conf: JPEG's quality and chroma subsampling, and its density, which
/// darktable's export module leaves in `metadata/resolution`, the print dpi in the cm and
/// inch modes and 300 in the others (`_dimensions_type_changed`); PNG's bit depth and
/// compression. Numbers are kept whole, so one read with decimals is rounded.
pub fn format(store: &Store, format: FileFormat) -> Format {
    match format {
        FileFormat::Jpeg => Format::Jpeg(jpeg::Options {
            quality: store.get(&EXPORT_JPEG_QUALITY).round() as u8,
            subsample: store.get(&EXPORT_JPEG_SUBSAMPLE),
            dpi: match store.get(&EXPORT_SIZE_MODE) {
                SizeMode::Cm | SizeMode::Inch => store.get(&EXPORT_SIZE_DPI).round() as u16,
                SizeMode::Pixels | SizeMode::Scale => jpeg::Options::default().dpi,
            },
        }),
        FileFormat::Png => Format::Png(png::Options {
            bit_depth: store.get(&EXPORT_PNG_BIT_DEPTH),
            compression: store.get(&EXPORT_PNG_COMPRESSION).round() as u8,
        }),
    }
}

